/* crc16.cpp —— CRC-16/CCITT-FALSE 的两种实现
 *
 * 编译：见同级目录的 test_crc16.cpp
 */

#include "crc16.h"
#include <stdio.h>

/* ============================================================
 * 多项式：0x1021
 *
 * 二进制展开（17 位里的低 16 位有效）：
 *   0001 0000 0010 0001
 *    ↑         ↑    ↑   ↑
 *    bit16    bit12 bit5 bit0
 *
 * 对应数学式 x^16 + x^12 + x^5 + 1
 *
 * 为什么只写 16 位（0x1021）而不写 17 位？
 * 因为 x^16 那一项是"隐含的最高位"，在所有 CRC 实现里都不参与异或，
 * 所以业界约定：多项式常量只写低 16 位。
 * ============================================================ */
#define CRC16_POLY      0x1021
#define CRC16_INIT      0xFFFF

/* ============================================================
 * 实现一：逐位运算
 *
 * 算法本质是"模 2 长除法"（GF(2) 多项式除法）的移位实现：
 *   - 用 16 位寄存器当"滑窗"
 *   - 每来一个字节，把它异或进寄存器的高 8 位
 *   - 然后做 8 次：
 *       看最高位是不是 1（是 → 说明"这一位够除"）
 *       整体左移一位
 *       若刚才最高位是 1 → 异或上多项式（等价于长除法里的"做一次减法"）
 *   - 所有位处理完，寄存器里剩下的就是余数 = CRC
 * ============================================================ */
uint16_t crc16_bitwise(const uint8_t *data, size_t len)
{
    uint16_t crc = CRC16_INIT;               /* ① 初始值 0xFFFF（变体规定） */

    for (size_t i = 0; i < len; i++) {       /* ② 遍历每个字节 */
        crc ^= (uint16_t)(data[i] << 8);     /* ③ 把当前字节异或进"高 8 位" */

        for (int bit = 0; bit < 8; bit++) {  /* ④ 一个字节 8 个 bit */
            if (crc & 0x8000) {              /* ⑤ 最高位（bit15）是 1？ */
                crc = (uint16_t)((crc << 1) ^ CRC16_POLY);
            } else {
                crc = (uint16_t)(crc << 1);
            }
            crc &= 0xFFFF;                   /* ⑥ 只保留低 16 位（扔掉溢出的第 17 位） */
        }
    }

    return crc;
}

/* ============================================================
 * 实现二：查表法
 *
 * 核心思想：把"处理一个字节要做的 8 次循环"预先算好存进表里。
 *
 * 逐位版每个字节做 8 次循环；查表版每个字节只做 1 次查表 + 1 次异或。
 * 结果是完全一样的，只是速度快 8 倍。
 * ============================================================ */

static uint16_t crc_table[256];     /* 256 项，每项 2 字节，共 512 字节 */
static int      table_ready = 0;

/* 建表：对每个可能的字节值 (0..255)，单独跑一遍"逐位算法" */
static void build_crc_table(void)
{
    for (int i = 0; i < 256; i++) {
        /* ① 把字节放到高 8 位，低 8 位补 0 —— 和逐位版的 ③ 是同一步 */
        uint16_t crc = (uint16_t)((uint16_t)i << 8);

        /* ② 做完全相同的 8 次逐位运算 */
        for (int bit = 0; bit < 8; bit++) {
            if (crc & 0x8000) {
                crc = (uint16_t)((crc << 1) ^ CRC16_POLY);
            } else {
                crc = (uint16_t)(crc << 1);
            }
            crc &= 0xFFFF;
        }

        /* ③ 存进表 —— 这就是"输入字节 i 单独作用 8 轮"的完整结果 */
        crc_table[i] = crc;
    }
    table_ready = 1;
}

uint16_t crc16_table(const uint8_t *data, size_t len)
{
    if (!table_ready) {
        build_crc_table();
    }

    uint16_t crc = CRC16_INIT;

    for (size_t i = 0; i < len; i++) {
        /* ④ 决定查表下标：
         *    (crc >> 8) —— 取 CRC 的高 8 位（"当前正在处理的那部分"）
         *    ^ data[i]  —— 异或上新字节，等价于逐位版的 crc ^= (byte << 8) 的效果
         */
        uint8_t look = (uint8_t)((crc >> 8) ^ data[i]);

        /* ⑤ 一次完成"左移 8 位 + 8 次条件异或" */
        crc = (uint16_t)((crc << 8) ^ crc_table[look]);
    }

    return crc;
}

/* ============================================================
 * 打印表（8 列一行，方便肉眼核对；也是你以后想硬编码表时的现成素材）
 * ============================================================ */
void crc16_print_table(void)
{
    if (!table_ready) {
        build_crc_table();
    }

    printf("static const uint16_t crc16_table[256] = {\n");
    for (int i = 0; i < 256; i++) {
        if (i % 8 == 0) {
            printf("    ");
        }
        printf("0x%04X, ", crc_table[i]);
        if (i % 8 == 7) {
            printf("\n");
        }
    }
    printf("};\n");
}
